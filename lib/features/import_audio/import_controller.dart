// Riverpod wiring of the recording import: the importer, the platform
// decoder, and the one background import job with its progress, which the
// meetings screen shows and can cancel.

import 'dart:async';
import 'dart:io';

import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../core/errors.dart';
import '../../session/providers.dart';
import 'audio_decoder.dart';
import 'import_store.dart';
import 'recording_importer.dart';
import 'strings.dart';

/// The platform decoder (null where there is none: only WAV imports work).
/// Android, iOS and Windows have one; overridden in tests.
final nativeAudioDecoderProvider = Provider<NativeAudioDecoder?>((ref) {
  if (Platform.isAndroid || Platform.isIOS || Platform.isWindows) {
    return const MethodChannelAudioDecoder();
  }
  return null;
});

/// Stored details of imported recordings.
final importInfoStoreProvider = Provider<ImportInfoStore>(
  (ref) => ImportInfoStore(ref.watch(databaseProvider)),
);

/// The details of one imported meeting (null for recorded meetings).
final importInfoProvider = FutureProvider.autoDispose
    .family<ImportInfo?, String>(
      (ref, meetingId) => ref.watch(importInfoStoreProvider).load(meetingId),
    );

/// The importer over the app's repositories and engines.
final recordingImporterProvider = Provider<RecordingImporter>((ref) {
  final paths = ref.watch(appPathsProvider);
  return RecordingImporter(
    meetings: ref.watch(meetingRepositoryProvider),
    post: ref.watch(postProcessorProvider),
    settings: ref.watch(appSettingsProvider),
    engines: ref.watch(sessionEnginesFactoryProvider),
    recordingsDir: paths.recordingsDir,
    store: ref.watch(importInfoStoreProvider),
    decoder: ImportAudioDecoder(native: ref.watch(nativeAudioDecoderProvider)),
  );
});

/// Phase of the import job.
enum ImportPhase {
  /// Nothing to show.
  idle,

  /// Importing.
  running,

  /// Done (see [ImportJobState.meetingId]).
  succeeded,

  /// Failed (see [ImportJobState.errorAr]).
  failed,

  /// Cancelled by the user.
  cancelled,
}

/// State of the import job.
class ImportJobState {
  /// Creates a state.
  const ImportJobState({
    this.phase = ImportPhase.idle,
    this.fileName,
    this.progress = 0,
    this.statusAr,
    this.errorAr,
    this.noticeAr,
    this.meetingId,
    this.cancelling = false,
    this.needsModels = false,
  });

  /// Phase.
  final ImportPhase phase;

  /// File being imported.
  final String? fileName;

  /// 0..1.
  final double progress;

  /// Status line while running.
  final String? statusAr;

  /// Error after a failure.
  final String? errorAr;

  /// Notice after success.
  final String? noticeAr;

  /// The imported meeting (also kept after a transcription failure).
  final String? meetingId;

  /// Cancel requested, still cleaning up.
  final bool cancelling;

  /// The failure is about speech models / keys (offer the models screen).
  final bool needsModels;

  /// True while running.
  bool get isRunning => phase == ImportPhase.running;

  /// Copy with changes.
  ImportJobState copyWith({
    double? progress,
    String? statusAr,
    bool? cancelling,
  }) => ImportJobState(
    phase: phase,
    fileName: fileName,
    progress: progress ?? this.progress,
    statusAr: statusAr ?? this.statusAr,
    errorAr: errorAr,
    noticeAr: noticeAr,
    meetingId: meetingId,
    cancelling: cancelling ?? this.cancelling,
    needsModels: needsModels,
  );
}

/// Runs one import at a time in the background (see [RecordingImporter]);
/// after the transcript is ready the minutes are generated by the meeting's
/// [MeetingJobsController] like after a recording.
class ImportJobController extends Notifier<ImportJobState> {
  ImportCancelToken? _token;
  Future<String?>? _running;

  @override
  ImportJobState build() => const ImportJobState();

  void _set(ImportJobState s) {
    if (ref.mounted) state = s;
  }

  /// Why an import cannot start now (Arabic), or null.
  String? busyReason() {
    if (_running != null) return IS.busy;
    final session = ref.read(meetingSessionControllerProvider);
    if (session.isActive) return IS.recordingActive;
    return null;
  }

  /// Starts importing [request]; completes with the new meeting id (null on
  /// failure / cancellation, see [state]). Never throws.
  Future<String?> start(ImportRequest request) {
    final busy = busyReason();
    if (busy != null) {
      _set(
        ImportJobState(
          phase: ImportPhase.failed,
          fileName: request.fileName,
          errorAr: busy,
        ),
      );
      return Future.value();
    }
    final token = _token = ImportCancelToken();
    _set(
      ImportJobState(
        phase: ImportPhase.running,
        fileName: request.fileName,
        statusAr: IS.checking,
      ),
    );
    final importer = ref.read(recordingImporterProvider);
    final meetings = ref.read(meetingRepositoryProvider);
    String? createdId;
    final f = () async {
      try {
        final outcome = await importer.importFile(
          request,
          cancel: token,
          onMeetingCreated: (id) => createdId = id,
          onProgress: (p) {
            if (!state.isRunning) return;
            _set(
              state.copyWith(
                progress: p.fraction,
                statusAr: state.cancelling ? IS.cancelling : p.statusAr,
              ),
            );
          },
        );
        _set(
          ImportJobState(
            phase: ImportPhase.succeeded,
            fileName: request.fileName,
            progress: 1,
            meetingId: outcome.meetingId,
            noticeAr: outcome.failedSegments > 0
                ? IS.doneWithFailures(outcome.failedSegments)
                : IS.done,
          ),
        );
        if (ref.mounted) {
          unawaited(
            ref
                .read(meetingJobsProvider(outcome.meetingId).notifier)
                .generateMinutes(automatic: true),
          );
        }
        return outcome.meetingId;
      } on OperationCancelledException {
        _set(
          ImportJobState(
            phase: ImportPhase.cancelled,
            fileName: request.fileName,
            noticeAr: IS.cancelled,
          ),
        );
        return null;
      } catch (e) {
        // A transcription failure keeps the meeting (with its audio).
        String? kept;
        final id = createdId;
        if (id != null) {
          try {
            if (await meetings.get(id) != null) kept = id;
          } catch (_) {
            // No link then.
          }
        }
        _set(
          ImportJobState(
            phase: ImportPhase.failed,
            fileName: request.fileName,
            errorAr: e is InsatoException ? e.messageAr : IS.unexpected,
            meetingId: kept,
            needsModels: e is ModelException || e is MissingApiKeyException,
          ),
        );
        return null;
      }
    }();
    _running = f;
    return f.whenComplete(() {
      _running = null;
      if (identical(_token, token)) _token = null;
    });
  }

  /// Requests cancellation of the running import.
  void cancel() {
    final t = _token;
    if (t == null || !state.isRunning) return;
    t.cancel();
    _set(state.copyWith(cancelling: true, statusAr: IS.cancelling));
  }

  /// Hides a finished job's card.
  void dismiss() {
    if (_running == null) _set(const ImportJobState());
  }
}

/// The recording import job (one at a time).
final importJobProvider = NotifierProvider<ImportJobController, ImportJobState>(
  ImportJobController.new,
);
